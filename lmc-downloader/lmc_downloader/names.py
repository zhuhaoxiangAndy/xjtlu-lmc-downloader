"""Windows-safe naming shared by the crawler and the fetcher.

The rules mirror ``build_dir_tree.sanitize_name`` on purpose: a directory tree
generated by ``build-dir-tree`` and a download performed by this package must
agree on every name, otherwise files land outside the folders that were built
for them. Keep the two in sync if either changes.

Policy
------
* Only characters Windows cannot store are touched: ``< > : " / \\ | ? *`` and
  control characters. Everything else is preserved verbatim, including runs of
  spaces, ``&``, parentheses, brackets and non-ASCII text.
* Trailing dots and spaces are removed because Windows silently drops them,
  which would make a written name differ from the recorded one.
* Reserved device names (``CON``, ``NUL``, ``COM1`` ...) get a trailing
  underscore so the file can actually be created.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Dict, Optional
from urllib.parse import unquote, urlparse

ILLEGAL_CHARS = re.compile(r'[<>:"/\\|?*\x00-\x1f]')

RESERVED_NAMES = frozenset(
    ["CON", "PRN", "AUX", "NUL"]
    + ["COM%d" % i for i in range(1, 10)]
    + ["LPT%d" % i for i in range(1, 10)]
)

#: Extension inferred from a MIME type when the server sends no file name.
EXTENSION_BY_MIME = {
    "application/pdf": ".pdf",
    "application/msword": ".doc",
    "application/vnd.openxmlformats-officedocument.wordprocessingml.document": ".docx",
    "application/vnd.ms-powerpoint": ".ppt",
    "application/vnd.openxmlformats-officedocument.presentationml.presentation": ".pptx",
    "application/vnd.ms-excel": ".xls",
    "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet": ".xlsx",
    "application/zip": ".zip",
    "application/x-zip-compressed": ".zip",
    "text/plain": ".txt",
    "text/csv": ".csv",
    # 用户要求：网页一律存成 .mhtml，便于浏览器原样打开
    "text/html": ".mhtml",
    "application/xhtml+xml": ".mhtml",
    "application/json": ".json",
    "image/png": ".png",
    "image/jpeg": ".jpg",
    "video/mp4": ".mp4",
}

#: Names the server may return that carry no information; never use them as-is.
GENERIC_NAMES = frozenset(
    ["", ".", "..", "view.php", "pluginfile.php", "download", "index.php",
     "file", "unnamed", "download_folder.php"]
)

MAX_NAME_LENGTH = 180


def sanitize_name(text: str, replacement: str = "") -> str:
    """Return a name Windows can store, preserving everything else verbatim."""
    if text is None:
        return ""
    name = ILLEGAL_CHARS.sub(replacement, text)
    name = name.strip("\r\n\t")
    # Windows drops trailing dots/spaces, so drop them here to stay truthful.
    name = name.rstrip(" .")
    if not name or name in (".", ".."):
        return ""
    stem = name.split(".", 1)[0].upper()
    if stem in RESERVED_NAMES:
        name = name + "_"
    if len(name) > MAX_NAME_LENGTH:
        stem, dot, suffix = name.rpartition(".")
        if dot and len(suffix) <= 12:
            keep = MAX_NAME_LENGTH - len(suffix) - 1
            name = stem[:keep] + "." + suffix
        else:
            name = name[:MAX_NAME_LENGTH]
    return name


def split_parts(relative: str) -> list:
    """Split a relative POSIX-ish path into sanitized parts."""
    parts = []
    for raw in relative.replace("\\", "/").split("/"):
        if raw in ("", ".", ".."):
            continue
        cleaned = sanitize_name(raw)
        if cleaned:
            parts.append(cleaned)
    return parts


def unique_path(directory, name: str) -> Path:
    """Never overwrite: append `` (n)`` before the suffix until the name is free."""
    directory = Path(directory)
    candidate = directory / name
    if not candidate.exists():
        return candidate
    stem, suffix = candidate.stem, candidate.suffix
    index = 1
    while True:
        candidate = directory / ("%s (%d)%s" % (stem, index, suffix))
        if not candidate.exists():
            return candidate
        index += 1


def filename_from_disposition(value: Optional[str]) -> str:
    """Parse ``Content-Disposition``, preferring the RFC 5987 ``filename*`` form."""
    if not value:
        return ""
    extended = re.search(r"filename\*\s*=\s*([^']*)'[^']*'([^;]+)", value, re.I)
    if extended:
        charset = (extended.group(1) or "utf-8").strip() or "utf-8"
        raw = extended.group(2).strip().strip('"')
        try:
            return unquote(raw, encoding=charset, errors="replace")
        except LookupError:
            return unquote(raw)
    quoted = re.search(r'filename\s*=\s*"([^"]*)"', value, re.I)
    if quoted:
        return quoted.group(1)
    plain = re.search(r"filename\s*=\s*([^;]+)", value, re.I)
    if plain:
        return plain.group(1).strip().strip('"')
    return ""


def filename_from_url(url: str) -> str:
    """Last path segment of a URL, percent-decoded."""
    try:
        path = urlparse(url).path
    except ValueError:
        return ""
    return unquote(path.rsplit("/", 1)[-1])


def extension_for_mime(content_type: Optional[str]) -> str:
    if not content_type:
        return ""
    mime = content_type.split(";")[0].strip().lower()
    return EXTENSION_BY_MIME.get(mime, "")


HTML_SUFFIXES = (".html", ".htm", ".xhtml")


def as_mhtml(name: str, content_type: Optional[str] = None) -> str:
    """Turn a web-page filename into ``.mhtml``.

    Two things reach this point as HTML: a Moodle ``page`` module, and a
    ``resource`` whose viewer page could not be resolved to a real file. Both are
    web pages, and the user asked for those to be stored as ``.mhtml`` so the
    browser opens them with their assets inlined instead of as a bare document.
    """
    mime = (content_type or "").split(";")[0].strip().lower()
    is_web = mime in ("text/html", "application/xhtml+xml")
    suffix = Path(name).suffix.lower()
    if not is_web and suffix not in HTML_SUFFIXES:
        return name
    stem = Path(name).stem if suffix else name
    return (stem or "page") + ".mhtml"


def choose_filename(
    disposition: Optional[str],
    url: str,
    fallback: str,
    content_type: Optional[str] = None,
) -> str:
    """Pick the most trustworthy available file name.

    Order: ``Content-Disposition`` > URL basename > activity title. A MIME
    extension is appended only when the winner has no extension at all.
    """
    candidates = [
        filename_from_disposition(disposition),
        filename_from_url(url),
        fallback,
    ]
    name = ""
    for candidate in candidates:
        cleaned = sanitize_name(candidate)
        if cleaned and cleaned.lower() not in GENERIC_NAMES:
            name = cleaned
            break
    if not name:
        name = sanitize_name(fallback) or "download"
    if not Path(name).suffix:
        extension = extension_for_mime(content_type)
        if extension:
            name += extension
    return name


def human_bytes(count: int) -> str:
    """Render a byte count for human-facing output."""
    value = float(count)
    for unit in ("B", "KiB", "MiB", "GiB", "TiB"):
        if value < 1024 or unit == "TiB":
            if unit == "B":
                return "%d B" % int(value)
            return "%.1f %s" % (value, unit)
        value /= 1024.0
    return "%d B" % count


def manifest_key(section: str, activity: str, name: str) -> str:
    """Stable identity for one item inside a manifest."""
    return "/".join(split_parts(section) + [sanitize_name(activity) or "", name])
